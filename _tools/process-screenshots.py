#!/usr/bin/env python3
"""File new screenshots from _screenshots/inbox/ into assets/images/.

Name each upload after its shot ID from _screenshots/shots.json (for example
COOK-1.jpg or cook-1.png). This script resizes it to 1280px wide, strips
metadata, saves it as assets/images/<folder>/<slug>.jpg, removes it from the
inbox, and rewrites _screenshots/SHOT-LIST.md so the list shows what's done.
Files whose names don't match a shot ID are left in the inbox and listed, to
be placed by hand. Placing the image on its page and writing the caption is
done by hand afterwards, from what the screenshot actually shows.

Run from the repo root:  python3 _tools/process-screenshots.py
"""
import json
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
INBOX = ROOT / "_screenshots" / "inbox"
SHOTS = json.loads((ROOT / "_screenshots" / "shots.json").read_text())
BY_ID = {s["id"].lower(): s for s in SHOTS}
EXTS = {".jpg", ".jpeg", ".png", ".webp"}


def target(shot):
    return ROOT / "assets" / "images" / shot["folder"] / f"{shot['slug']}.jpg"


filed, unmatched = [], []
for f in sorted(INBOX.iterdir()):
    if f.suffix.lower() not in EXTS:
        continue
    shot = BY_ID.get(f.stem.lower())
    if not shot:
        unmatched.append(f.name)
        continue
    im = ImageOps.exif_transpose(Image.open(f)).convert("RGB")
    if im.width > 1280:
        im = im.resize((1280, round(im.height * 1280 / im.width)), Image.LANCZOS)
    out = target(shot)
    out.parent.mkdir(parents=True, exist_ok=True)
    im.save(out, "JPEG", quality=84, optimize=True, progressive=True)  # no exif passed: metadata dropped
    f.unlink()
    filed.append((shot, out, im.size))

lines = [
    "# Screenshot shot list",
    "",
    "Generated by `_tools/process-screenshots.py` from `shots.json`. Upload a",
    "capture to `_screenshots/inbox/` named after its ID (e.g. `COOK-1.jpg`).",
    "Tier 1 replaces wiki art on the most-used pages; tier 3 is nice to have.",
    "",
    "| Done | ID | Tier | Page | Shot | How to get it |",
    "|---|---|---|---|---|---|",
]
for s in SHOTS:
    done = "✅" if target(s).exists() else ""
    page = s["page"].split("/")[-1].rsplit(".", 1)[0]
    lines.append(f"| {done} | {s['id']} | {s['tier']} | {page} | {s['shot']} | {s['how']} |")
(ROOT / "_screenshots" / "SHOT-LIST.md").write_text("\n".join(lines) + "\n")

for shot, out, size in filed:
    print(f"filed {shot['id']} -> {out.relative_to(ROOT)} {size[0]}x{size[1]}  (page: {shot['page']})")
for name in unmatched:
    print(f"no shot ID matches {name}; left in the inbox")
done = sum(target(s).exists() for s in SHOTS)
print(f"{done}/{len(SHOTS)} shots done")
